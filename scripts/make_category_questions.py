"""Turn the example questions in config/categories.yaml into an evaluation seed set: eval/category_questions.yaml.

Each question keeps its category, the attributes that would answer it, and `status: unlabelled`: the expected
answers are filled in later (from official data and the lab's recordings), never by hand-checking.

    python scripts/make_category_questions.py
"""

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
cats = yaml.safe_load((ROOT / "config/categories.yaml").read_text())
qs = []
for cid, c in cats.items():
    attrs = c.get("attributes", []) + list((c.get("new_attributes") or {}))
    for i, q in enumerate(c["asks"], 1):
        qs.append(
            {
                "id": f"{cid}-{i}",
                "category": cid,
                "priority": c["priority"],
                "question": q,
                "attributes": attrs,
                "status": "unlabelled",
            }
        )
out = ROOT / "eval/category_questions.yaml"
out.write_text(
    "# Generated by scripts/make_category_questions.py from config/categories.yaml. Do not edit by hand.\n"
    + yaml.safe_dump(qs, sort_keys=False, width=120)
)
print(f"wrote {out.relative_to(ROOT)}: {len(qs)} questions in {len(cats)} categories")
